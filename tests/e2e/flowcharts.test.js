'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { withApp, readSteps } = require('./lib/fixtures');
const { openLibrary, openGuideCard, eventually } = require('./lib/flows');

test('flowchart toolbar, visual/block placement, editing, undo and Markdown step links work in the real editor', () => withApp('flowchart-editor', {}, async (app, env) => {
  await openLibrary(app); await openGuideCard(app, 'Reset a password');
  const guideDir = path.join(env.dataDir, 'library/guides/guide-sample-reset-password');
  const before = readSteps(guideDir)[0];
  const original = fs.readFileSync(path.join(before.dir, before.step.image.workingPath));
  await app.selectOption('.main-visual-select', 'Flowchart');
  await app.waitForVisible('.flowchart-toolbar');
  assert.equal(await app.isVisible('.image-tools'), false);
  assert.match(await app.evaluate('getComputedStyle(document.querySelector(".canvas-wrap")).backgroundImage'), /radial-gradient/);
  await app.clickText('Decision', { scope: '.flowchart-toolbar' });
  await app.clickText('Add node', { scope: '.flowchart-toolbar' });
  await app.clickText('Undo', { scope: '.flowchart-toolbar' });
  await eventually(async () => (await app.evaluate('document.querySelectorAll(".flowchart-surface [data-node-id]").length')) === 1, 'node creation undone');
  await app.clickText('Redo', { scope: '.flowchart-toolbar' });
  await eventually(async () => (await app.evaluate('document.querySelectorAll(".flowchart-surface [data-node-id]").length')) === 2, 'node creation redone');
  await app.clickText('Connect', { scope: '.flowchart-toolbar' });
  await app.click('.flowchart-surface [data-node-id]:first-of-type');
  await app.click('.flowchart-surface [data-node-id]:last-of-type');
  await eventually(async () => (await app.evaluate('document.querySelectorAll(".flowchart-surface [data-edge-id]").length')) === 1, 'connected nodes');
  await app.click('.flowchart-surface [data-edge-id]');
  await app.setValue('.flowchart-properties input', 'Yes'); await app.key('Tab');
  await app.clickText('Select', { scope: '.flowchart-toolbar' });
  await app.click('.flowchart-surface [data-node-id]:last-of-type');
  await app.setValue('.flowchart-properties input', 'Sign in'); await app.key('Tab');
  const destinationLabel = await app.evaluate(`document.querySelector('.flowchart-properties select[aria-label="Go to step"]').options[2].textContent`);
  await app.selectOption('.flowchart-properties select[aria-label="Go to step"]', destinationLabel);
  const nodePoint = await app.waitForVisible('.flowchart-surface [data-node-id]:last-of-type');
  await app.drag(nodePoint, { x: nodePoint.x - 10, y: nodePoint.y + 30 });
  await eventually(async () => (await app.evaluate('document.querySelector(".flowchart-surface [data-node-id]:last-of-type rect").getAttribute("y")')) === '70', 'node dragged');
  await app.screenshot('flowchart-canvas-editor.png');
  await app.selectOption('.flowchart-toolbar select', 'Content block');
  await app.clickText('Done', { scope: '.flowchart-toolbar' });
  await app.waitForVisible('.image-tools');
  assert.equal(await app.isVisible('.flowchart-toolbar'), false);
  await app.key('s', { ctrl: true });
  await eventually(() => readSteps(guideDir)[0].step.flowchartBlocks?.length === 1, 'flowchart block saved');
  assert.deepEqual(fs.readFileSync(path.join(before.dir, before.step.image.workingPath)), original);

  await app.selectOption('select[aria-label="Description editing mode"]', 'Markdown');
  await eventually(async () => !(await app.evaluate('document.querySelector(".description-source").readOnly')), 'Markdown source ready');
  await app.setValue('.description-source', '# Overview\n\n_Italic_ and **bold**\n\n| A | B |\n| --- | --- |\n| 1 | 2 |\n\n');
  const targetId = readSteps(guideDir)[1].stepId;
  await app.type(`[Step](step:${targetId})`);
  await app.clickText('Preview', { scope: '.description-mode' });
  await app.waitForVisible('.description-preview h1');
  assert.equal(await app.evaluate('document.querySelector(".description-preview em").textContent'), 'Italic');
  assert.equal(await app.evaluate('document.querySelectorAll(".description-preview table td").length'), 2);
  assert.equal(await app.evaluate('document.querySelector(".description-preview a").textContent'), 'Step 2');
  await app.key('s', { ctrl: true });
  await eventually(() => /\[Step\]\(step:/.test(readSteps(guideDir)[0].step.descriptionMarkdown || ''), 'permanent step link saved');
  await app.screenshot('flowchart-markdown-preview.png');
  const saved = readSteps(guideDir)[0].step;
  assert.equal(saved.flowchartBlocks[0].graph.edges[0].label, 'Yes');
  const target = readSteps(guideDir).find(s => s.stepId === targetId);
  await app.click('.description-preview a');
  await eventually(async () => (await app.evaluate(`document.querySelector('input[aria-label="Step title"]').value`)) === target.step.title, 'step link navigated');
}));

test('descriptions default to Rich text, insert numbered Step links in the toolbar, and toggle Markdown preview separately', () => withApp('description-controls', {}, async (app, env) => {
  await openLibrary(app); await openGuideCard(app, 'Reset a password');
  const mode = 'select[aria-label="Description editing mode"]';
  assert.equal(await app.evaluate(`document.querySelector('${mode}').value`), 'rich');
  assert.deepEqual(await app.evaluate(`Array.from(document.querySelector('${mode}').options, o => o.textContent)`), ['Rich text', 'Markdown']);
  assert.equal(await app.isVisible('.description-preview-toggle'), false);
  assert.equal(await app.evaluate('document.querySelector(".rich-toolbar [data-action=insertStep]").previousElementSibling.textContent'), 'Clear');
  await app.setValue('.rich-editor[contenteditable]', 'Before after');
  for (let i = 0; i < 6; i++) await app.key('ArrowLeft');
  await app.clickText('Step', { scope: '.rich-toolbar' });
  await app.clickText('Insert', { scope: '#modal-root' });
  assert.equal(await app.evaluate('document.querySelector(".rich-editor[contenteditable] a").textContent'), 'Step 2');
  assert.equal((await app.evaluate('document.querySelector(".rich-editor[contenteditable]").textContent')).replace(/\u00a0/g, ' '), 'BeforeStep 2 after');
  const guideDir = path.join(env.dataDir, 'library/guides/guide-sample-reset-password');
  await eventually(() => /data-step-id=/.test(readSteps(guideDir)[0].step.descriptionHtml), 'numbered link saved with permanent ID');
  await app.selectOption(mode, 'Markdown');
  await eventually(async () => !(await app.evaluate('document.querySelector(".description-source").readOnly')), 'rich text converted to Markdown');
  assert.equal(await app.isVisible('.rich-toolbar [data-action=insertStep]'), false);
  assert.equal(await app.isVisible('.description-preview-toggle'), true);
  await app.setValue('.description-source', '# Heading\n\n**Bold**');
  const activeColor = await app.evaluate('getComputedStyle(document.querySelector(".pane-steps button.primary")).backgroundColor');
  await app.clickText('Preview', { scope: '.description-mode' });
  await app.waitForVisible('.description-preview h1');
  assert.equal(await app.evaluate('document.querySelector(".description-preview-toggle").textContent'), 'Editor');
  assert.equal(await app.evaluate('document.querySelector(".description-preview-toggle").getAttribute("aria-pressed")'), 'true');
  await eventually(async () => (await app.evaluate('getComputedStyle(document.querySelector(".description-preview-toggle")).backgroundColor')) === activeColor, 'preview button highlighted blue');
  assert.equal(await app.isVisible('.description-source'), false);
  await app.screenshot('description-markdown-toggle.png');
  await app.clickText('Editor', { scope: '.description-mode' });
  await app.waitForVisible('.description-source');
  assert.equal(await app.evaluate('document.querySelector(".description-preview-toggle").getAttribute("aria-pressed")'), 'false');
  assert.equal(await app.evaluate('document.querySelector(".description-preview-toggle").textContent'), 'Preview');
  await app.selectOption(mode, 'Rich text');
  assert.equal(await app.isVisible('.description-preview-toggle'), false);
  assert.equal(await app.isVisible('.rich-toolbar [data-action=insertStep]'), true);
  assert.equal(await app.evaluate('document.querySelector(".rich-editor[contenteditable] h1").textContent'), 'Heading');
}));
